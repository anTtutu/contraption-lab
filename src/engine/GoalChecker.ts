import type { PropBase } from './PropBase';

/** 目标检测上下文：引擎每步传给检测器的只读信息 */
export interface GoalCheckContext {
  /** 当前全局步进计数 */
  tick: number;
  /** 已累积虚拟运行时长（ms，受倍速影响） */
  virtualRunMs: number;
  /** 世界内全部道具（目标判定按 pid 关联道具实例） */
  props: readonly PropBase[];
}

/**
 * 目标检测器：引擎在 RUNNING 态每固定步调用一次
 * 实现方应保证幂等（同一时刻多次调用结果一致）且轻量（每步都会执行）。
 */
export interface GoalChecker {
  /**
   * 执行一次目标检测
   * @param ctx 检测上下文
   * @returns 本次检测新达成的目标数量；>0 时引擎迁移到 SUCCESS
   */
  check(ctx: GoalCheckContext): number;
}
